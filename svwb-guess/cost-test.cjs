const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const E=require('./engine.js'),S=require('./semantics.js');
let id=0;
const card=text=>({id:++id,name:'测试'+id,type:1,class:0,cost:4,rarity:1,attack:2,health:2,tribes:[],text,evolvedText:text,effects:[]});
const fixed=card('在手牌中发动。自己的随从超进化时，使本卡牌的费用变为0。');
const subtract=card('在手牌中发动。自己的随从超进化时，使本卡牌的费用-3。');
const temporary=card('在手牌中发动。自己的原始费用为3的随从超进化时，回合结束前，使本卡牌的费用变为0。');
const ordinary=card('在手牌中发动。自己的随从进化时，使本卡牌的费用-3。');
const enemy=card('在手牌中发动。对手的随从超进化时，使本卡牌的费用-3。');
const higher=card('使本卡牌的费用变为8。');
const ally=card('使自己的手牌中的1个随从的费用-3。');
const buff=card('自己的回合结束时，使自己的战场上的随机1个超进化后的随从+1/+1。');
const auto=card('使自己的战场上的1个进化前的随从超进化。');
const plainAuto=card('使自己的战场上的1个进化前的随从进化。');
const extract=c=>S.extract(c),first=c=>extract(c)[0];
assert.equal(first(fixed).action,'减费');
assert.equal(first(fixed).costMode,'设为');
assert.deepEqual(first(fixed).numbers,['0'],'Zero is the resulting cost, not zero discount');
assert.equal(first(subtract).costMode,'减少');
assert.equal(first(temporary).duration,'本回合');
assert.equal(first(temporary).condition,'原始费用=3');
assert.equal(first(subtract).duration,'持续');
assert.equal(first(temporary).activation,'手牌');
assert.equal(first(higher).action,'费用设定','Setting cost above printed cost must not imply a discount');
assert.equal(first(enemy).side,'己','Opponent evolution still changes this player’s own card cost');
assert.notEqual(first(enemy).event,first(subtract).event);
assert.equal(first(ally).costMode,undefined,'Another target’s cost is not this card’s self discount');
assert.deepEqual(extract(buff).map(e=>e.action),['加身材']);
assert(![...E.features(buff).keys()].some(k=>/自动.*进化/.test(k)));
assert.deepEqual(extract(auto).map(e=>e.action),['超进化']);
assert.deepEqual(extract(plainAuto).map(e=>e.action),['进化']);
assert(S.similarity(extract(fixed),extract(subtract))>.8);
assert(S.similarity(extract(fixed),extract(subtract))<1);
assert(S.similarity(extract(fixed),extract(temporary))<1);
assert(S.similarity(extract(subtract),extract(ordinary))>S.similarity(extract(subtract),extract(enemy)));
const deck=[fixed,subtract,temporary,ordinary,enemy,higher,ally,buff,auto,plainAuto],engine=E.createEngine(deck);
assert(engine.compare(temporary,subtract).skill>engine.compare(temporary,buff).skill);
for(const a of deck)for(const b of deck){const score=engine.compare(a,b).score;assert(score>=0&&score<=100);assert(Math.abs(score-engine.compare(b,a).score)<1e-8);}
const ctx={window:{}};vm.runInNewContext(fs.readFileSync(__dirname+'/data.js','utf8'),ctx);
const cards=JSON.parse(JSON.stringify(ctx.window.SVWB_GUESS_DATA.cards)),real=E.createEngine(cards),find=name=>cards.find(c=>c.name===name);
const mary=find('梅格的挚友·玛丽亲'),vic=find('深渊探究者·维切');
assert.equal(first(mary).event,first(vic).event);
assert(!extract(mary).some(e=>e.action==='超进化'));
const ranks=real.rank(mary,E.poolFor(cards)),vicRank=ranks.find(r=>r.card.id===vic.id);
assert(vicRank.rank<=10&&vicRank.score>35,'Shared evolution-triggered hand discount should no longer be rank 67 with zero semantic affinity');
assert(ranks.find(r=>r.card.name==='曲行工兵').rank<=10);
console.log('PASS: self cost setting/subtraction, evolution events, hand activation, temporary/conditional limits, false evolution exclusion, symmetry.');
console.log({name:vic.name,rank:vicRank.rank,score:vicRank.score.toFixed(2)});
